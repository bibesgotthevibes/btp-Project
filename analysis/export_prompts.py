"""
analysis/export_prompts.py
──────────────────────────
Writes docs/ner_pipeline_prompts.md: every prompt used by the NER-guided
simplification pipeline, verbatim from the code, with the purpose of each stage
and one fully assembled real example (DS-01, Qwen) taken from the saved results.

Run: python analysis/export_prompts.py
"""

import sys
import json
from pathlib import Path

CURRENT_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = CURRENT_DIR.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from analysis.config import RESULTS_DIR
from analysis.prompts import ner_extraction_prompts as ner
from analysis.prompts.builder import (
    PROMPT_REGISTRY, NER_GUIDED_SYSTEM_PROMPTS, build_ner_extraction_prompt, build_ner_guided_prompt,
)
from analysis.prompts.json_parser import ner_json_to_retention_block

OUT_MD = CURRENT_DIR / "docs" / "ner_pipeline_prompts.md"
TYPES = [("discharge", "Discharge summaries"), ("pathology", "Pathology reports"), ("radiology", "Radiology (MRI) reports")]
PLACEHOLDER = "<<REPORT TEXT>>"


def block(text: str, lang: str = "text") -> str:
    fence = "````" if "```" in text else "```"
    return f"{fence}{lang}\n{text.rstrip()}\n{fence}\n"


def main():
    md = []
    add = md.append

    add("# NER-guided simplification: prompts at every stage\n")
    add("Generated by `analysis/export_prompts.py` from the prompt code, so the text below is exactly what the "
        "pipeline sends. `" + PLACEHOLDER + "` marks where the source report is inserted.\n")

    add("## How the pipeline uses them\n")
    add("| Stage | What it does | Purpose | Call settings |\n|---|---|---|---|")
    add("| 1. Entity extraction | Sends the report with a domain-specific extraction prompt; the model returns one JSON object | Pull every clinically important fact (diagnoses, values, procedures, medications, follow-up, grading, findings…) into a structured checklist | temperature 0.1, max 4,096 tokens; 2 messages (system + user) |")
    add("| 1b. Parse | `parse_json_from_llm_response` strips `<think>` blocks and code fences, then tries direct JSON, fenced JSON, and the first `{…}` block | Make the extraction robust to formatting noise | No API call. If parsing fails, the run falls back to the zero-shot prompt |")
    add("| 1c. Retention block | `ner_json_to_retention_block` turns the JSON into a readable list headed \"YOU MUST RETAIN ALL OF THESE\" | Give the simplifier an explicit, human-readable checklist instead of raw JSON | No API call |")
    add("| 2. Guided simplification | The domain simplification prompt with the retention block inserted, plus a retention rule | Rewrite the report in plain language while keeping every listed entity | temperature 0.2, max 4,096 tokens; 2 messages (system + user) |")
    add("| Fallback / baseline | The plain zero-shot simplification prompt (no entity block, no retention rule) | Used when stage 1 fails, and as the comparison condition | temperature 0.2, max 4,096 tokens |")
    add("")
    add("> **Note on the one-shot extraction example.** `ner_extraction_prompts.py` also defines a worked example "
        "(an example report and its JSON) for each document type, placed between the system prompt and the real "
        "request. The runner sends only the system prompt and the final user message, so **this example is never sent**; "
        "stage 1 runs zero-shot. The examples are listed in the appendix for completeness. The discharge example is 91% "
        "identical to the DS-01 test report and contains warning signs that are not in that report, so it should be "
        "replaced before it is ever enabled.\n")

    for dt, label in TYPES:
        add(f"## {label}\n")

        ner_sys, ner_user, _ = build_ner_extraction_prompt(dt, PLACEHOLDER)
        add("### Stage 1: entity extraction\n")
        add("**Purpose:** extract every clinical entity of this document type into JSON with a fixed schema. "
            "The schema also asks for lay explanations and severity labels, and (for discharge summaries) normal "
            "ranges \"if inferable from medical knowledge\" and warning signs. These inferred fields are later "
            "shown to the simplifier as facts it must retain.\n")
        add("**System prompt**\n")
        add(block(ner_sys))
        add("**User message**\n")
        add(block(ner_user))

        add("### Stage 2: NER-guided simplification\n")
        add("**Purpose:** rewrite the report for a patient or family while keeping every entity from stage 1. "
            "`{ner_retention_block}` is replaced by the retention block built from the stage-1 JSON "
            "(see the assembled example at the end).\n")
        add("**System prompt (template)**\n")
        add(block(NER_GUIDED_SYSTEM_PROMPTS[(dt, "simplification")]))
        _, guided_user, _ = build_ner_guided_prompt("simplification", dt, PLACEHOLDER, {})
        add("**User message**\n")
        add(block(guided_user))

        zs = PROMPT_REGISTRY[(dt, "simplification")]
        add("### Fallback and baseline: zero-shot simplification\n")
        add("**Purpose:** the same task without an entity list. Used when stage 1 fails to parse, and as the "
            "\"without NER\" condition in the comparison. Its rules match the NER-guided prompt except for the "
            "entity block and the retention rule.\n")
        add("**System prompt**\n")
        add(block(zs["system"]))
        add("**User message**\n")
        add(block("\n".join(["--- Your Task ---", f"Please {zs['task_label']}:\n", f"Original Medical Report:\n{PLACEHOLDER}\n", "Output:\n"])))

    # Real assembled example from the saved results
    ckpt = RESULTS_DIR / ".checkpoints" / "simplification_discharge_DS-01_cerebras_qwen38_ner-guided.json"
    if ckpt.exists():
        r = json.loads(ckpt.read_text(encoding="utf-8"))
        add("## Assembled example: DS-01, Qwen 3.8\n")
        add("What the model actually received and returned for one report, taken from the saved run.\n")
        add("**Stage 1 output (parsed JSON)**\n")
        add(block(json.dumps(r["ner_extraction_json"], indent=2, ensure_ascii=False), "json"))
        add("**Retention block built from it** (inserted into the stage-2 system prompt)\n")
        add(block(ner_json_to_retention_block(r["ner_extraction_json"], "discharge")))
        add("**Stage 2 system prompt as sent**\n")
        add(block(r["system_prompt"]))
        add("**Stage 2 user message as sent**\n")
        add(block(r["user_prompt"]))
        add("**Stage 2 output**\n")
        add(block(r["output_text"]))
        add("Lines in the output such as the creatinine reference range and the list of warning signs come from "
            "fields the extraction prompt asked the model to infer, not from the report.\n")

    add("## Appendix: one-shot extraction examples (defined but not sent)\n")
    for dt, label in TYPES:
        prefix = dt.upper()
        add(f"### {label}\n")
        add("**Example input**\n")
        add(block(getattr(ner, f"{prefix}_NER_FEW_SHOT_INPUT")))
        add("**Example output**\n")
        add(block(getattr(ner, f"{prefix}_NER_FEW_SHOT_OUTPUT"), "json"))

    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text("\n".join(md), encoding="utf-8")
    print(f"Wrote {OUT_MD} ({OUT_MD.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
