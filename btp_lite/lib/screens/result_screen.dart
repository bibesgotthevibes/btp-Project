import 'package:flutter/material.dart';
import 'package:flutter_animate/flutter_animate.dart';
import 'package:flutter_markdown/flutter_markdown.dart';
import 'package:flutter/services.dart';
import 'package:google_fonts/google_fonts.dart';
import 'package:printing/printing.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:share_plus/share_plus.dart';
import '../models/api_model.dart';
import '../models/simplify_result.dart';
import '../widgets/chat_panel.dart';

class ResultScreen extends StatefulWidget {
  final SimplifyResult result;
  const ResultScreen({super.key, required this.result});

  @override
  State<ResultScreen> createState() => _ResultScreenState();
}

class _ResultScreenState extends State<ResultScreen>
    with SingleTickerProviderStateMixin {
  late TabController _tabController;

  @override
  void initState() {
    super.initState();
    _tabController = TabController(length: 2, vsync: this);
  }

  @override
  void dispose() {
    _tabController.dispose();
    super.dispose();
  }

  Future<void> _downloadPdf(BuildContext context) async {
    final doc = pw.Document();
    final dateStr =
        '${widget.result.timestamp.day}/${widget.result.timestamp.month}/${widget.result.timestamp.year}';

    doc.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(40),
        header: (_) => pw.Container(
          padding: const pw.EdgeInsets.only(bottom: 12),
          decoration: const pw.BoxDecoration(
            border: pw.Border(
              bottom: pw.BorderSide(color: PdfColor.fromInt(0xFF6C4DF6), width: 2),
            ),
          ),
          child: pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Text(
                'Simplified Discharge Summary',
                style: const pw.TextStyle(
                  fontSize: 20,
                  fontWeight: pw.FontWeight.bold,
                  color: PdfColor.fromInt(0xFF6C4DF6),
                ),
              ),
              pw.SizedBox(height: 4),
              pw.Text(
                'Generated by MedSimplify Lite  ·  $dateStr  ·  Model: ${widget.result.modelName}',
                style: const pw.TextStyle(
                    fontSize: 9, color: PdfColor.fromInt(0xFF8B949E)),
              ),
            ],
          ),
        ),
        footer: (_) => pw.Container(
          alignment: pw.Alignment.center,
          padding: const pw.EdgeInsets.only(top: 12),
          child: pw.Text(
            'For medical guidance, always consult a qualified healthcare professional.  |  For research use only.',
            style: const pw.TextStyle(
                fontSize: 8, color: PdfColor.fromInt(0xFF8B949E)),
            textAlign: pw.TextAlign.center,
          ),
        ),
        build: (_) => [
          pw.Text(
            widget.result.simplifiedText,
            style: const pw.TextStyle(fontSize: 11, lineSpacing: 5),
          ),
        ],
      ),
    );

    await Printing.layoutPdf(
      onLayout: (_) async => doc.save(),
      name: 'simplified_discharge_summary.pdf',
    );
  }

  @override
  Widget build(BuildContext context) {
    final isDark = Theme.of(context).brightness == Brightness.dark;
    final bgColor = isDark ? const Color(0xFF0D1117) : const Color(0xFFF5F7FA);
    final cardColor = isDark ? const Color(0xFF1C2333) : Colors.white;
    final borderColor =
        isDark ? const Color(0xFF30363D) : const Color(0xFFE5E7EB);
    final textColor =
        isDark ? const Color(0xFFE6EDF3) : const Color(0xFF1A1A2E);
    final subColor =
        isDark ? const Color(0xFF8B949E) : const Color(0xFF6B7280);

    final resolvedModel = ApiModel.all.firstWhere(
      (m) => m.name == widget.result.modelName || m.id == widget.result.modelName,
      orElse: () => ApiModel.all.first,
    );

    return Scaffold(
      backgroundColor: bgColor,
      appBar: AppBar(
        backgroundColor: isDark ? const Color(0xFF161B22) : Colors.white,
        leading: IconButton(
          icon: const Icon(Icons.arrow_back_rounded),
          onPressed: () => Navigator.pop(context),
        ),
        title: Text('Summary & Assistant',
            style: GoogleFonts.inter(
                fontWeight: FontWeight.w700, color: textColor)),
        actions: [
          IconButton(
            icon: const Icon(Icons.share_rounded),
            tooltip: 'Share',
            onPressed: () => Share.share(widget.result.simplifiedText,
                subject: 'Simplified Discharge Summary — MedSimplify'),
          ),
          IconButton(
            icon: const Icon(Icons.picture_as_pdf_rounded),
            tooltip: 'Download PDF',
            onPressed: () => _downloadPdf(context),
          ),
          IconButton(
            icon: const Icon(Icons.copy_rounded),
            tooltip: 'Copy text',
            onPressed: () async {
              await Clipboard.setData(
                  ClipboardData(text: widget.result.simplifiedText));
              if (context.mounted) {
                ScaffoldMessenger.of(context).showSnackBar(
                  const SnackBar(content: Text('Copied to clipboard ✓')),
                );
              }
            },
          ),
        ],
        bottom: TabBar(
          controller: _tabController,
          labelColor: const Color(0xFF6C4DF6),
          unselectedLabelColor: subColor,
          indicatorColor: const Color(0xFF6C4DF6),
          labelStyle: GoogleFonts.inter(fontWeight: FontWeight.w600, fontSize: 13),
          tabs: const [
            Tab(icon: Icon(Icons.description_rounded, size: 18), text: 'Summary'),
            Tab(icon: Icon(Icons.forum_rounded, size: 18), text: 'Chat Assistant'),
          ],
        ),
      ),
      body: TabBarView(
        controller: _tabController,
        children: [
          // ── TAB 1: Summary ──────────────────────────────────────────────────
          SingleChildScrollView(
            padding: const EdgeInsets.all(20),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                // Meta chips
                Wrap(
                  spacing: 8,
                  runSpacing: 8,
                  children: [
                    _MetaChip(
                      label: '🤖 ${widget.result.modelName}',
                      color: const Color(0xFF6C4DF6),
                    ),
                    _MetaChip(
                      label: widget.result.strategy,
                      color: const Color(0xFF10B981),
                    ),
                    if (widget.result.tokensUsed != null)
                      _MetaChip(
                        label: '${widget.result.tokensUsed} tokens',
                        color: subColor,
                        isLight: true,
                      ),
                    _MetaChip(
                      label:
                          '${widget.result.timestamp.day}/${widget.result.timestamp.month}/${widget.result.timestamp.year}',
                      color: subColor,
                      isLight: true,
                    ),
                  ],
                ),
                const SizedBox(height: 16),
                // Ask question CTA banner
                Container(
                  padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 12),
                  decoration: BoxDecoration(
                    color: const Color(0xFF6C4DF6).withValues(alpha: 0.08),
                    borderRadius: BorderRadius.circular(14),
                    border: Border.all(
                        color: const Color(0xFF6C4DF6).withValues(alpha: 0.2)),
                  ),
                  child: Row(
                    children: [
                      const Icon(Icons.chat_bubble_outline_rounded,
                          color: Color(0xFF6C4DF6), size: 20),
                      const SizedBox(width: 10),
                      Expanded(
                        child: Text(
                          'Have follow-up questions about medicines or precautions?',
                          style: GoogleFonts.inter(
                            fontSize: 12,
                            fontWeight: FontWeight.w500,
                            color: textColor,
                          ),
                        ),
                      ),
                      TextButton(
                        onPressed: () => _tabController.animateTo(1),
                        child: const Text('Open Chat →'),
                      ),
                    ],
                  ),
                ),
                const SizedBox(height: 16),
                // Result card
                Container(
                  width: double.infinity,
                  padding: const EdgeInsets.all(20),
                  decoration: BoxDecoration(
                    color: cardColor,
                    borderRadius: BorderRadius.circular(16),
                    border: Border.all(color: borderColor),
                  ),
                  child: MarkdownBody(
                    data: widget.result.simplifiedText,
                    styleSheet: MarkdownStyleSheet(
                      p: GoogleFonts.inter(
                          fontSize: 15, color: textColor, height: 1.8),
                      strong: GoogleFonts.inter(
                          fontSize: 15,
                          fontWeight: FontWeight.w600,
                          color: textColor),
                    ),
                  ),
                ).animate().fadeIn(duration: 350.ms).slideY(
                    begin: 0.05,
                    end: 0,
                    duration: 350.ms,
                    curve: Curves.easeOut),
                const SizedBox(height: 16),
                // Disclaimer
                Container(
                  padding: const EdgeInsets.all(14),
                  decoration: BoxDecoration(
                    color: const Color(0xFFEFF6FF),
                    borderRadius: BorderRadius.circular(12),
                    border: Border.all(color: const Color(0xFFBFDBFE)),
                  ),
                  child: Row(
                    children: [
                      const Icon(Icons.info_outline_rounded,
                          color: Color(0xFF3B82F6), size: 18),
                      const SizedBox(width: 10),
                      Expanded(
                        child: Text(
                          'Research use only. Simplified summaries are generated by AI and may contain errors. Always consult a qualified healthcare professional.',
                          style: GoogleFonts.inter(
                            fontSize: 12,
                            color: const Color(0xFF1E40AF),
                            height: 1.5,
                          ),
                        ),
                      ),
                    ],
                  ),
                ),
                const SizedBox(height: 80),
              ],
            ),
          ),

          // ── TAB 2: Chat Assistant ───────────────────────────────────────────
          Padding(
            padding: const EdgeInsets.all(16),
            child: ChatPanel(
              result: widget.result,
              model: resolvedModel,
              isCompact: false,
            ),
          ),
        ],
      ),
    );
  }
}

class _MetaChip extends StatelessWidget {
  final String label;
  final Color color;
  final bool isLight;

  const _MetaChip({
    required this.label,
    required this.color,
    this.isLight = false,
  });

  @override
  Widget build(BuildContext context) {
    return Container(
      padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 5),
      decoration: BoxDecoration(
        color: color.withValues(alpha: isLight ? 0.07 : 0.12),
        borderRadius: BorderRadius.circular(20),
      ),
      child: Text(
        label,
        style: GoogleFonts.inter(
          fontSize: 12,
          fontWeight: FontWeight.w500,
          color: color,
        ),
      ),
    );
  }
}
